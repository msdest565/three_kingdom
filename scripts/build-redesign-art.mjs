// Bundles real game art (hero portraits + equipment icons) for the offline design draft docs/v1/ui-redesign-v2.html.
// Classic script output so the draft opens from file:// without a server.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { heroPortrait } from '../hero-portraits.js';
import { equipmentIcon } from '../equipment-art.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const heroes = ['guan_yu', 'cao_cao', 'xiahou_dun', 'zhao_yun'];
const icons = [
  ['signature_guan_yu_weapon', 'gold'], ['basic_armor', 'purple'], ['basic_command_token', 'blue'], ['signature_guan_yu_horse', 'red'],
  ['basic_weapon', 'white'], ['basic_weapon', 'blue'], ['basic_weapon', 'purple'], ['basic_weapon', 'red'],
  ['basic_armor', 'white'], ['basic_armor', 'blue'], ['basic_armor', 'red'],
  ['basic_command_token', 'white'], ['basic_command_token', 'purple'], ['basic_command_token', 'red'],
  ['basic_horse', 'white'], ['basic_horse', 'blue'], ['basic_horse', 'purple'],
  ['signature_cao_cao_weapon', 'gold'], ['signature_zhao_yun_horse', 'red'],
];
const art = { hero: {}, gear: {} };
for (const id of heroes) art.hero[id] = heroPortrait(id);
for (const [id, q] of icons) art.gear[`${id}:${q}`] = equipmentIcon(id, q);
const out = path.join(root, 'docs', 'v1', 'ui-redesign-v2-art.js');
await writeFile(out, `// Generated by scripts/build-redesign-art.mjs — do not edit.\nwindow.ART = ${JSON.stringify(art)};\n`);
console.log('wrote', path.relative(root, out), Object.keys(art.hero).length, 'heroes,', Object.keys(art.gear).length, 'icons');
