"""Subset the OFL brush display face to the characters the UI actually shows.

Usage: python scripts/build-font.py <path-to-MaShanZheng-Regular.ttf>
Writes assets/fonts/brush-subset.woff2 and brush-font.css (data URI, so the
single-file dist stays offline). Re-run after adding new display copy.
Requires fonttools + brotli (pip install fonttools==4.55.3 brotli==1.1.0).
"""
import base64, json, pathlib, re, subprocess, sys
from fontTools import subset

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else root / 'assets/fonts/MaShanZheng-Regular.ttf')

# Display copy: names, titles and UI labels. Story prose stays in the body face.
data = json.loads(subprocess.check_output(['node', '-e', """
import('./runtime-data.js').then(({BALANCE, CONTENT}) => {
  const out = [];
  for (const h of Object.values(BALANCE.heroes)) out.push(h.name, h.ultimate?.name || '');
  for (const c of Object.values(BALANCE.camps)) out.push(c.name);
  for (const t of Object.values(BALANCE.metaProgression.equipment.templates)) out.push(t.name);
  for (const l of CONTENT.levels) out.push(l.name);
  for (const c of CONTENT.chapters) out.push(c.title || '');
  for (const m of CONTENT.maps) out.push(m.name);
  process.stdout.write(JSON.stringify(out));
});"""], cwd=root, text=True, encoding='utf-8'))
# Only text the CSS sets in the brush face (titles, seals, primary buttons, banners).
# Copy wrapped in data-brush="..." markers in index.html/campaign-app.js is also collected.
ui = ''.join((root / f).read_text(encoding='utf-8') for f in ['index.html', 'campaign-app.js'])
chars = set(''.join(data)) | set(''.join(re.findall(r'data-brush="([^"]*)"', ui)))
# Brush-set surfaces in code: sheet titles, wave banners, headings, advice glyphs and camp glyphs.
for pattern in [r"openModal\(([^)]*)\)", r"banner\(([^;]*)\)", r"<h[23][^>]*>([^<]*)</h[23]>", r"ADVICE_ROUTE = \{([^}]*)\}", r"campGlyphs = \{([^}]*)\}", r"label\(([^)]*)\)"]:
    for chunk in re.findall(pattern, ui):
        chars |= set(re.findall(r'[㐀-鿿]', chunk))
chars |= set('魏蜀吴篇将战守住了城破下一阵出阵再战军帐晒重第一二三四五六七八九十终波敌军来袭敌将压境连斩横扫一击无双人新纪录胜利箱开启工坊科技锻造背包武将征战设置整备研究升级换装册铜铁粮暂停选项战术本局整军备战学习守关迎敌布阵关')
chars |= set('0123456789·×＋')
text = ''.join(sorted(chars))

out = root / 'assets/fonts/brush-subset.woff2'
options = subset.Options(); options.flavor = 'woff2'; options.layout_features = ['*']; options.name_IDs = ['*']; options.name_languages = ['*']
font = subset.load_font(str(src), options); sub = subset.Subsetter(options); sub.populate(text=text); sub.subset(font)
subset.save_font(font, str(out), options)
b64 = base64.b64encode(out.read_bytes()).decode()
css = ('/* Ma Shan Zheng (马善政毛笔楷书), SIL Open Font License 1.1, see assets/fonts/OFL.txt.\n'
       '   Subset generated by scripts/build-font.py; do not edit by hand. */\n'
       '@font-face{font-family:"WSBrush";font-style:normal;font-weight:400;font-display:swap;'
       f'src:url(data:font/woff2;base64,{b64}) format("woff2")}}\n')
(root / 'brush-font.css').write_text(css, encoding='utf-8')
print(f'{len(text)} chars -> {out.stat().st_size // 1024} KB woff2, brush-font.css {len(css) // 1024} KB')
